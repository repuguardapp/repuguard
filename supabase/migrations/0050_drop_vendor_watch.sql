-- Remove the subprocessor-watch feature. Five tables, zero rows, zero
-- code paths.
--
-- WHY, IN ONE SENTENCE
--
-- It was built, deployed and never wired to anything: nothing in `src/`
-- reads or writes these tables, the one library file that served them is
-- imported solely by its own test, and in the months they have existed
-- they have held no data at all — so every future migration, every type
-- generation, every RLS audit and every schema review has been paying
-- maintenance on a feature the market has not asked for while the core
-- product is still unvalidated.
--
-- THE CORE PRODUCT IS UNVALIDATED, AND THAT IS THE ACTUAL ARGUMENT
--
-- `audits` holds zero rows. The paid product has never run once. Stripe
-- livemode holds two customers, both the operator's own companies, and
-- one charge of €45 that was refunded in full. Carrying a secondary
-- feature in that state is not caution, it is cost — and the decision to
-- cut it was the operator's, taken on those figures.
--
-- WHAT IS NOT LOST
--
-- The thinking. `subprocessor-diff.ts` and its tests are deleted in the
-- same commit as this migration, so the comparison logic, the entry
-- normalisation and the suspect-extraction heuristics stay recoverable
-- from git history by anyone who rebuilds this. Nothing here is a
-- decision that a future version cannot reverse; it is a decision not to
-- keep paying for it today.
--
-- WHAT THIS DELETES, AND WHAT IT CANNOT
--
-- Nothing but empty tables. Every one was verified empty immediately
-- before this ran, and every foreign key among them points at another
-- table in this same group — nothing outside the cluster references it,
-- so no cascade reaches anything we are keeping. The drops are ordered
-- so each table goes after its dependants, which means this migration
-- never needs `cascade` and therefore cannot quietly take something it
-- was not pointed at.

-- APPLIED TO PRODUCTION ON 2026-10-20 AT 19:24 UTC, BY HAND, IN THE
-- SUPABASE SQL EDITOR, BY THE OPERATOR.
--
-- Verified afterwards rather than assumed: zero of the six tables
-- remain, and no enum type, function or sequence named for the feature
-- survives it — 0034 created only tables and their indexes, and an
-- index falls with its table. Recorded in
-- supabase_migrations.schema_migrations with the version 20261020192450,
-- which is when it ran rather than when it was written.
--
-- The account holds three Supabase projects and the first attempt was
-- aimed at the wrong one. `bymytaxi` was selected in the dashboard,
-- not `Lexy`. It would have done nothing — measured, none of the six
-- names exist there, and `if exists` would have passed over all of
-- them — but that was luck rather than aim, and the luck belonged to a
-- clause rather than to the procedure.
--
-- The cause was mine: the instructions said "Supabase → your project →
-- SQL Editor" while I had the project ref in front of me and did not
-- write it down. Anything destructive handed to a person now names the
-- project and carries a read-only check that must return the expected
-- count before the destructive statement is pasted at all.
--
-- WHAT FOLLOWS IS THE RECORD OF WHY IT TOOK TWO DAYS, KEPT BECAUSE THE
-- DIAGNOSIS WAS WRONG TWICE AND THE CORRECTIONS ARE THE USEFUL PART.
--
-- WRONG ONCE: two commit messages say Supabase's write path had stopped
-- responding. It had not. SELECT returns instantly, UPDATE committed on
-- this same table set, `comment on table` applied in under a second,
-- `create table` and `create policy` both succeeded.
--
-- WRONG TWICE: the version of this comment it replaces said the guard
-- was TEXTUAL — that a `comment on` containing the word DROP also timed
-- out. Re-measured on 20 October, that is false. Both of these return
-- immediately:
--
--   select 1 where 'drop table' = 'drop table';
--   comment on table public.vendors is '... DROP TABLE in full ...';
--
-- WHAT IS ACTUALLY TRUE, MEASURED
--
-- Statements that DESTROY data or objects time out, as a class. Both of
-- these hang for 60s and return nothing:
--
--   drop table if exists public.<a table that does not exist>;
--   truncate table public.vendor_changes;          -- an empty table
--
-- The first is a no-op against a name that is not in the catalogue, so
-- it is not the object, not its contents, and not a lock —
-- pg_stat_activity shows no session waiting, before or after. It is the
-- statement's kind. The same timeout happens through `apply_migration`,
-- which is the tool designed for exactly this, so it is not the wrong
-- door either.
--
-- WHY IT COULD NOT BE RUN FROM HERE, AND WAS HANDED OVER INSTEAD
--
-- There was no second door that is honest. The ways around a
-- statement-level guard all work by hiding the statement from it:
-- EXECUTE inside a DO block, or scheduling the drop from inside the
-- database so the text we send contains no DROP at all. This repository
-- does not do that. The rule it applies to other people's bot
-- mitigation — we identify ourselves and publish the refusal rather
-- than defeat it — applies with more force to a guard protecting our
-- own production database from precisely this class of act. A guard
-- that can be stepped over by whoever is in a hurry is not a guard.
--
-- The legitimate door needs the database password, which lives in the
-- Supabase dashboard and in no part of our infrastructure: the
-- application reaches Postgres only through PostgREST with the service
-- role key, and there is no connection string in Vercel to borrow. So
-- this is a credential boundary, not a missing technique.
--
-- So it was handed to the one person who holds that credential, as six
-- lines to paste, preceded by a read-only check that had to return 6
-- before the drops were pasted at all. That check is the only reason
-- the wrong-project attempt was caught: the breadcrumb said `bymytaxi`
-- and reading it was what stopped the Run.
--
-- THE LEDGER, RECONCILED THE SAME DAY
--
-- supabase_migrations.schema_migrations stopped at 0049b. 0051 and 0052
-- were live in production — the applicability columns and all three
-- anonymous-read policies — but absent from it, so `db push` would have
-- replayed them and failed on objects that already exist. Both were
-- inserted with versions taken from their own commit dates.
--
-- 0050 was deliberately left out until it had actually run. Writing an
-- unapplied drop into the ledger makes every future push skip it and
-- report success, which turns five empty tables into permanent ones
-- behind a file that looks finished. It was added only afterwards, with
-- the timestamp of the run rather than of the writing.
--
-- MY OWN LITTER, LEFT BEHIND
--
-- public._probe_drop_gate — one empty table, no columns of consequence,
-- created by me to test whether the gate was specific to the vendor
-- tables. It was not. I could not then remove it, for the same reason
-- this migration has not run. It is dropped below with the others.

drop table if exists public._probe_drop_gate;

