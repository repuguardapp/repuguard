const SUPPORTED_LANGS = Object.keys(TRANSLATIONS);
const RTL_LANGS = ['ar'];

function detectLang() {
  const saved = localStorage.getItem('rg-lang');
  if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
  const browser = (navigator.language || navigator.userLanguage || 'fr').split('-')[0].toLowerCase();
  return SUPPORTED_LANGS.includes(browser) ? browser : 'fr';
}

function t(key) {
  const lang = window.RG_LANG || 'fr';
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS['fr'][key] || key;
}

function applyLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = 'fr';
  window.RG_LANG = lang;
  localStorage.setItem('rg-lang', lang);

  // RTL support
  document.documentElement.setAttribute('dir', RTL_LANGS.includes(lang) ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);

  // Apply data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
}

function initI18n() {
  const lang = detectLang();
  applyLang(lang);
}

